    _SHARED['m_rules'] = [norm(li.get_text(' ')) for li in mr.select('ul.rules li')]
    _SHARED['a_rules'] = [norm(li.get_text(' ')) for li in ar.select('ul.rules li')]
    for sec, cnt in ((mr, 'تقارير التاجر'), (ar, 'تقارير الإدارة')):
        sec.select_one('ul.rules').decompose()
        p = sec.find('p', class_='sub')
