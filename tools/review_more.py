def settings_section(S):
    rows = []
    for tr in S['settings'].select('tbody tr'):
        tds = tr.find_all('td')
        rows.append((norm(tds[0].get_text(' ')), tds[1].decode_contents(), norm(tds[2].get_text(' '))))
    num, sw, beh = [], [], []
    for n, v, lvl in rows:
        if n in BEHAVIOR:
            beh.append([('<b>%s</b>' % n), v, '<a class="rid" href="#%s">%s</a>' % (BEHAVIOR[n], BEHAVIOR[n])])
        elif n in SWITCH:
            sw.append(['<b>%s</b>' % n, v, '<span class="tag">%s</span>' % lvl])
        else:
            num.append(['<b>%s</b>' % n, v, '<span class="tag">%s</span>' % lvl, LIMITS.get(n, '—')])
