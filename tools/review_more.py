def cell_set(td, html):
    td.clear()
    td.append(BeautifulSoup('<x>%s</x>' % html, 'lxml').find('x'))
    td.find('x').unwrap()


def find_row(scope, first, nth=0):
    hits = [tr for tr in scope.select('tr') if tr.find(['td', 'th']) and norm(tr.find(['td', 'th']).get_text(' ')).startswith(first)]
    assert len(hits) > nth, ('صف غير موجود', first)
    return hits[nth]


