def catalog_wording(MODS):
    by = {r['id']: r for m in MODS for r in m['reqs']}
    def sub(rid, old, new, must=1):
        n = 0
        for f in ('rules', 'accept'):
            if old in by[rid][f]:
                by[rid][f] = by[rid][f].replace(old, new); n += 1
        assert n >= must, (rid, old[:50])
    sub('SYS-002', 'الأقسام، وأنواع المتاجر، والحالات، والرسوم، والمستويات، والحوافز، والرئيسية، والأدوار: جداول وإعدادات',
        'تُحفظ الأقسام وأنواع المتاجر والحالات والرسوم والمستويات والحوافز والرئيسية والأدوار في جداول وإعدادات لوحة الإدارة، ليتمكن المسؤول المخوّل من تعديلها دون إصدار نسخة جديدة')
    sub('SYS-002', 'قسم جديد أو مستوى جديد يُضاف دون كود', 'قسم جديد أو مستوى جديد من الأنواع المدعومة يُضاف من الإعدادات دون تطوير')
    hit = 0
    for rid in by:
        for f in ('rules', 'accept'):
            if 'صف موسمي يظهر دون إصدار' in by[rid][f]:
                by[rid][f] = by[rid][f].replace('صف موسمي يظهر دون إصدار', 'صف موسمي يُضاف من الإعدادات ويظهر دون إصدار جديد للتطبيق'); hit += 1
    assert hit
    sub('ADM-005', 'كل قاعدة (الحدث، المهلة، الرسالة، الحد الأقصى) تُعدَّل من الإعدادات بلا برمجة',
        'كل قاعدة (الحدث، المهلة، الرسالة، الحد الأقصى) تُعدَّل من الإعدادات دون تطوير', must=0)
    by['SYS-002']['title'] = 'الرسوم والمدد وحدود التشغيل في الإعدادات'
    # ربط ميسر: تحقق عملي لكل وسيلة دفع
    by['INT-001']['accept'] += '<li>نتائج تجربة الحجز والتحصيل والإلغاء والاسترداد موثّقة لكل وسيلة دفع معتمدة قبل الإطلاق، وما يخص ميسر مؤكد كتابةً ( D-11 )</li>'
    return MODS


