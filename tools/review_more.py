_SHARED = {}


def extract_shared(S, soup):
    """يستخرج القواعد المكررة من لوحة الإدارة وتقارير التاجر والإدارة ويجمعها في قسم واحد."""
    ad = S['admin-pages']
    rules_h3 = [h for h in ad.find_all('h3', recursive=False) if 'قواعد لكل صفحات' in h.get_text()][0]
    rules_ul = rules_h3.find_next_sibling('ul')
