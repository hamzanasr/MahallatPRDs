def fix_sections(S, soup):
    # ---- عدم تجاوب العميل: لا إنهاء تلقائي (ORD-008) ----
    d = S['app-driver']
    T(d, 'إنهاء تلقائي بعد 24:40', 'تنبيه الدعم بعد 24:40')
