import re
from bs4 import BeautifulSoup, NavigableString

VERSION = '3.3'
DATE = '30 سبتمبر 2026'
RANGE_100 = 'مسافة لا تتجاوز 100 متر بين موقع المندوب والنقطة المحددة'


def norm(t):
    return re.sub(r'\s+', ' ', t or '').strip()


def esc(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def T(scope, old, new, must=1):
    n = 0
    for s in list(scope.find_all(string=True)):
        if old in s:
            s.replace_with(NavigableString(str(s).replace(old, new)))
            n += 1
    assert n >= must, ('لم يوجد النص', old[:70], n)
    return n


def frag(soup, html):
    return BeautifulSoup(html, 'lxml').body.find(True)


