def fix_catalog(MODS):
    by = {r['id']: r for m in MODS for r in m['reqs']}

    def sub(rid, old, new, fields=('rules', 'accept'), must=1):
        n = 0
        for f in fields:
            if old in by[rid][f]:
                by[rid][f] = by[rid][f].replace(old, new)
                n += 1
        assert n >= must, (rid, old[:60])

    # نطاق الـ100 متر
    sub('ORD-005', 'الاستلام والتسليم داخل قطر 100 متر من المكان',
        'الاستلام والتسليم على ' + RANGE_100 + ' (المتجر عند الاستلام، والعميل عند التسليم)')
    sub('ORD-005', 'التأكيد خارج 100 متر غير ممكن',
        'تأكيد الاستلام أو التسليم غير ممكن إذا زادت المسافة بين موقع المندوب والنقطة المحددة على 100 متر')

    # إخفاء أرقام العميل واستثناء «اتصل بي»
    sub('MER-006', 'يظهر العميل والمندوب برقم تعريف فقط، بلا أسماء ولا أرقام تواصل',
        'يظهر العميل والمندوب برقم تعريف فقط، بلا أسماء ولا أرقام تواصل. الاستثناء الوحيد رقم «اتصل بي» بشروطه في MER-032')
    sub('MER-006', 'لا يظهر للتاجر اسم أو رقم عميل أو مندوب',
        'لا يظهر للتاجر اسم أو رقم جوال لعميل أو مندوب، عدا رقم «اتصل بي» الذي يظهر بشروط MER-032 فقط')
    by['MER-032']['rules'] += '<li>يختفي الرقم عند رد العميل، أو عند تطبيق «احذفه» بعد انتهاء مهلة الـ3 دقائق، أو عند إغلاق الطلب</li>'
    by['MER-032']['accept'] += ('<li>الرقم لا يظهر في قائمة الطلبات ولا في تفاصيل الطلب ولا في تقارير التاجر، ولا يظهر إلا لصنف ضُغط عليه «نفد» في طلب اختار عميله «اتصل بي»</li>'
                                '<li>بعد رد العميل، أو انتهاء مهلة الـ3 دقائق، أو إغلاق الطلب، لا يظهر الرقم للتاجر</li>')
    # فاتورة المنتجات: استثناء طلب الكتابة
    sub('MER-036', 'فاتورة المنتجات لا تظهر للعميل',
        'فاتورة المنتجات لا تظهر للعميل، إلا في طلب الكتابة: يرى صورتها قبل السداد ( ORD-013 )', fields=('rules',))
    by['MER-036']['accept'] += '<li>في طلب الكتابة تظهر صورة الفاتورة للعميل قبل السداد، وفي غيره لا تظهر له</li>'
    # توزيع: تنبيه 3 دقائق وإنذار 5 دقائق
    sub('DSP-001', 'بلا مندوب: تنبيه لغرفة العمليات بعد 5 دقائق مع إسناد يدوي، وعند 15 دقيقة يتوقف العرض',
        'بلا مندوب: تنبيه لغرفة العمليات بعد 3 دقائق، وإنذار قوي بعد 5 دقائق مع إسناد يدوي، وعند 15 دقيقة يتوقف العرض', fields=('rules',))
    return MODS
