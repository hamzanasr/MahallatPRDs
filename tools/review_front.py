def tbl(head, rows, cls=''):
    h = ''.join('<th>%s</th>' % x for x in head)
    b = ''.join('<tr>%s</tr>' % ''.join('<td>%s</td>' % c for c in r) for r in rows)
    return '<div class="tbl %s"><table><thead><tr>%s</tr></thead><tbody>%s</tbody></table></div>' % (cls, h, b)


def ids_in(html):
    return set(re.findall(r'\b[A-Z]{3}-\d{3}\b', re.sub(r'<[^>]+>', ' ', html)))


def prio(r):
    return 'p1' if 'أساسي للإطلاق' in r['tags'] else ('p2' if 'مهم' in r['tags'] else 'p3')


def stats(MODS):
    rows, tot = [], {'p1': 0, 'p2': 0, 'p3': 0}
    for m in MODS:
        c = {'p1': 0, 'p2': 0, 'p3': 0}
        for r in m['reqs']:
            c[prio(r)] += 1
        for k in c:
            tot[k] += c[k]
        rows.append((m, c))
    return rows, tot


def dependency_conflicts(MODS):
    order = {'p1': 0, 'p2': 1, 'p3': 2}
    by = {r['id']: r for m in MODS for r in m['reqs']}
    out = []
    for rid, r in by.items():
        for ref in sorted(ids_in(r['rules'] + r['accept'])):
            if ref != rid and ref in by and order[prio(r)] < order[prio(by[ref])]:
                out.append((rid, prio(r), ref, prio(by[ref])))
    return out


