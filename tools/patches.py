def norm(t):
    return re.sub(r'\s+', ' ', t or '').strip()


def T(scope, old, new, must=1):
    """استبدال نص داخل عقدة نصية واحدة."""
    n = 0
    for s in list(scope.find_all(string=True)):
        if old in s:
            s.replace_with(NavigableString(str(s).replace(old, new)))
            n += 1
    assert n >= must, ('لم يوجد النص', old[:60], n)
    return n


def row(scope, first, nth=0):
    hits = []
    for tr in scope.select('tr'):
        tds = tr.find_all(['td', 'th'])
        if tds and norm(tds[0].get_text(' ')).startswith(first):
            hits.append(tr)
    assert len(hits) > nth, ('لم يوجد الصف', first, len(hits))
    return hits[nth]


def cell(tr, i, html):
    td = tr.find_all(['td', 'th'])[i]
    td.clear()
    td.append(BeautifulSoup('<x>%s</x>' % html, 'lxml').find('x'))
    td.find('x').unwrap()


def new_tag(soup, html):
    return BeautifulSoup(html, 'lxml').body.find(True)


